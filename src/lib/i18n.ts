const ZH_MAP = zh as Record<string, string>;
const EN_MAP = en as Record<string, string>;

export function translate(locale: Locale, key: string, vars?: MessageVars): string {
  const dict = locale === "en" ? EN_MAP : ZH_MAP;
  const template = dict[key] ?? ZH_MAP[key] ?? key;
  return interpolate(template, vars);
}

export function t(locale: Locale, key: MessageKey, vars?: MessageVars): string {
  return translate(locale, key, vars);
}

export function isMessageKey(key: string): key is MessageKey {
  return key in ZH_MAP;
}

